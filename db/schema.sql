-- ------------------------------------------------------------
-- ПРОФИЛИ ИГРОКОВ: одна строка на аккаунт
-- ------------------------------------------------------------
create table if not exists public.profiles (
    id           uuid primary key references auth.users (id) on delete cascade,
    username     text not null unique,          -- ники не повторяются
    created_at   timestamptz default now(),
    total_flips  integer default 0,             -- счётчик переворотов
    avatar_emoji text default '👤'::text         -- выбранный эмодзи
);

-- ------------------------------------------------------------
-- РЕКОРДЫ: одна строка на игрока на размер поля
-- ------------------------------------------------------------
create table if not exists public.records (
    id         bigint generated by default as identity primary key,
    user_id    uuid not null references auth.users (id) on delete cascade,
    username   text not null,                    -- денормализация: чтобы рейтинг читался одним запросом
    board_size text not null,                    -- '4x4' | '4x5' | '6x6'
    best_moves integer not null,
    best_time  integer,                          -- null = ещё не мерили время
    updated_at timestamptz default now(),
    unique (user_id, board_size)
);

-- ИСТОРИЯ ПАРТИЙ: одна строка на каждую доигранную игру
create table if not exists public.games (
    id         bigint generated by default as identity primary key,
    user_id    uuid not null references auth.users (id) on delete cascade,
    board_size text not null,               -- '4x4' | '4x5' | '6x6'
    moves      integer not null,
    seconds    integer not null,
    won        boolean not null default true,  -- пригодится, когда появятся режимы с проигрышем
    created_at timestamptz default now()
);

alter table public.games enable row level security;

-- Партии видны всем (как рекорды: секретов там нет, только статистика)
drop policy if exists "Партии видны всем" on public.games;
create policy "Партии видны всем"
    on public.games for select
    using (true);

-- Игрок добавляет только свои партии
drop policy if exists "Игрок добавляет свои партии" on public.games;
create policy "Игрок добавляет свои партии"
    on public.games for insert
    with check (auth.uid() = user_id);

-- ------------------------------------------------------------
-- ROW LEVEL SECURITY: кто что имеет право делать
-- ------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.records  enable row level security;

-- Профили видны всем (рейтинг, чужие профили; секретов там нет)
drop policy if exists "Профили видны всем" on public.profiles;
create policy "Профили видны всем"
    on public.profiles for select
    using (true);

-- Игрок создаёт только свой профиль (при регистрации)
drop policy if exists "Игрок создаёт свой профиль" on public.profiles;
create policy "Игрок создаёт свой профиль"
    on public.profiles for insert
    with check (auth.uid() = id);

-- Игрок обновляет только свой профиль (эмодзи, счётчик)
drop policy if exists "Игрок обновляет свой профиль" on public.profiles;
create policy "Игрок обновляет свой профиль"
    on public.profiles for update
    using (auth.uid() = id)
    with check (auth.uid() = id);

-- Убираем дубль политики обновления (второй такой же жил с прошлых версий)
drop policy if exists "users can update own profile" on public.profiles;

-- Рекорды видны всем (таблица лидеров)
drop policy if exists "Рекорды видны всем" on public.records;
create policy "Рекорды видны всем"
    on public.records for select
    using (true);

-- Игрок добавляет только свои рекорды
drop policy if exists "Игрок добавляет свои рекорды" on public.records;
create policy "Игрок добавляет свои рекорды"
    on public.records for insert
    with check (auth.uid() = user_id);

-- Игрок обновляет только свои рекорды
drop policy if exists "Игрок обновляет свои рекорды" on public.records;
create policy "Игрок обновляет свои рекорды"
    on public.records for update
    using (auth.uid() = user_id);

-- Игрок удаляет только свои рекорды
drop policy if exists "Игрок удаляет свои рекорды" on public.records;
create policy "Игрок удаляет свои рекорды"
    on public.records for delete
    using (auth.uid() = user_id);